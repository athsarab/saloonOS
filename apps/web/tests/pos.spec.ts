  const item = await db.catalogItem.create({ data: { tenantId, name: 'Coconut Repair Shampoo', category: 'Hair care', type: 'PRODUCT', priceLkr: '1850', trackInventory: true, stockQuantity: '10' } }); productId = item.id;
